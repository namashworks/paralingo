"""Generate docs/tools-reference.md from paralingo.agent_tools.TOOL_SPECS.

    python scripts/gen_tools_reference.py          # write the file
    python scripts/gen_tools_reference.py --check  # exit 1 if the file is out of date (used by tests)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from paralingo.agent_tools import TOOL_SPECS  # noqa: E402

OUT = ROOT / "docs" / "tools-reference.md"


def _type(schema: dict) -> str:
    t = schema.get("type", "")
    if "enum" in schema:
        return "one of: " + ", ".join(f"`{v}`" for v in schema["enum"])
    if t == "array":
        item = schema.get("items", {})
        return f"array of {item.get('type', 'items')}s"
    if isinstance(t, list):
        return " or ".join(t)
    rng = []
    if "minimum" in schema:
        rng.append(f"≥ {schema['minimum']}")
    if "maximum" in schema:
        rng.append(f"≤ {schema['maximum']}")
    return t + (f" ({', '.join(rng)})" if rng else "")


def _first_sentence(text: str) -> str:
    """First sentence, without treating abbreviations such as "e.g." as the end."""
    return re.split(r"(?<!e\.g)(?<!i\.e)\.\s", text, maxsplit=1)[0].rstrip(".") + "."


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    llm = [s for s in TOOL_SPECS if not s.get("pipeline")]
    pipe = [s for s in TOOL_SPECS if s.get("pipeline")]
    lines = [
        "# Agent tools reference",
        "",
        "<!-- Generated by scripts/gen_tools_reference.py from paralingo/agent_tools.py. Do not edit by hand. -->",
        "",
        "Paralingo exposes 11 tools in Anthropic, OpenAI and MCP formats:",
        "",
        "```python",
        "from paralingo import SpeechProfileTools",
        "",
        "tools = SpeechProfileTools(\"profiles\", agent_id=\"my-agent\", include_pipeline_tools=False)",
        "tools.definitions(\"anthropic\")   # or \"openai\" or \"mcp\"",
        "tools.execute(\"paralingo_get_summary\", {\"speaker_id\": \"caller-42\"})   # returns a JSON string",
        "```",
        "",
        "`execute` returns `{\"ok\": true, \"result\": ...}` or `{\"ok\": false, \"error\": \"...\"}` and never raises.",
        "",
        "| Tool | Who calls it | Purpose |",
        "|---|---|---|",
    ]
    for s in TOOL_SPECS:
        who = "Your pipeline code" if s.get("pipeline") else "LLM"
        lines.append(f"| [`{s['name']}`](#{s['name']}) | {who} | {_cell(_first_sentence(s['description']))} |")
    lines += ["", "**LLM tools** are safe to give a model. **Pipeline tools** are hidden when you create "
              "`SpeechProfileTools(..., include_pipeline_tools=False)`, because they need audio or change consent.", ""]
    for group, specs in (("LLM tools", llm), ("Pipeline tools", pipe)):
        lines += [f"## {group}", ""]
        for s in specs:
            schema = s["input_schema"]
            req = set(schema.get("required", []))
            lines += [f"### {s['name']}", "", s["description"], "", "| Parameter | Type | Required | Description |",
                      "|---|---|---|---|"]
            for name, p in schema.get("properties", {}).items():
                lines.append(f"| `{name}` | {_cell(_type(p))} | {'yes' if name in req else ''} | {_cell(p.get('description', ''))} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/tools-reference.md is out of date: run python scripts/gen_tools_reference.py")
            sys.exit(1)
        print("docs/tools-reference.md is up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")
